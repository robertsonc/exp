"""Generate the supercronic crontab from the config.

Light tests get one line per client, offset so the clients are spread evenly
across the interval: with 12 clients on a 300 s interval, client N fires
25 s after client N-1, and each client's DHCP, DNS and app runs are offset from
one another within its slot. Supercronic's 7-field syntax adds seconds and year:
    second minute hour day-of-month month day-of-week year
"""
from __future__ import annotations

from . import config as C

EXM = "/opt/exm/bin/exm"


def _every(interval_s: int, offset_s: int) -> str:
    if interval_s % 60 or 3600 % interval_s:
        raise C.ConfigError(f"interval {interval_s}s must be a whole number of minutes that divides an hour")
    step = interval_s // 60
    offset_s %= interval_s
    minute = offset_s // 60
    return f"{offset_s % 60} {minute}-59/{step} * * * * *" if step > 1 else f"{offset_s % 60} * * * * * *"


def generate(cfg: dict) -> str:
    s = cfg["schedule"]
    clients = C.clients(cfg)          # server ports run no client tests
    n = max(1, len(clients))
    jitter = int(s.get("jitter_s", 10))
    tests = [("dhcp", int(s.get("dhcp_interval_s", 300)), 0.0, "--auto-mode"),
             ("dns", int(s.get("dns_interval_s", 300)), 1 / 3, ""),
             ("apps", int(s.get("apps_interval_s", 300)), 2 / 3, "")]
    out = ["# Generated by `exm crontab` from " + cfg["_path"] + f" (config {cfg['_ver']}). Do not edit:",
           "# change the config and run `sudo exm apply`.",
           "# Fields: second minute hour day-of-month month day-of-week year", ""]
    for test, interval, phase, extra in tests:
        out.append(f"# {test}: every {interval}s per client, staggered {interval / n:.0f}s apart")
        slot = interval / n
        for i, c in enumerate(clients):
            offset = int(round(i * slot + phase * slot))
            line = f"{_every(interval, offset)} {EXM} run {test} {c['id']} --jitter {jitter}"
            out.append(line + (f" {extra}" if extra else ""))
        out.append("")
    hb = int(s.get("heartbeat_interval_s", s.get("gateway_interval_s", 10)))
    if hb:
        if hb >= 60 or 60 % hb:
            raise C.ConfigError(f"heartbeat_interval_s {hb} must be a number of seconds that divides a minute")
        out += [f"# heartbeat every {hb}s: link and gateway ping on every port, one DHCP DISCOVER, one DNS query",
                f"*/{hb} * * * * * * {EXM} heartbeat", ""]
    sp = int(s.get("speedtest_interval_s", 600))
    out += [f"# speed tests: one client per {sp}s slot, rotating clients and providers; never two at once",
            f"{_every(sp, 45)} {EXM} speedtest-next", "",
            "# dashboard summary as a result, for the collector's details tables",
            f"15 * * * * * * {EXM} summary --emit", "",
            "# status snapshot for non-root readers: /var/lib/exm/status.json",
            f"30 * * * * * * {EXM} status --write --quiet", "",
            "# drop results older than retention_days",
            f"0 17 3 * * * * {EXM} prune", ""]
    return "\n".join(out)
