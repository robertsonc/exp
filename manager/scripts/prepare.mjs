#!/usr/bin/env node
// Generates worker/.generated/install-sh.ts: the bootstrap script the Worker serves at /install.sh.
// Uses <repo>/agent/install/install.sh when it exists (picked automatically), else a placeholder that
// exits 1 ("agent bootstrap not built yet"). Placeholders @@MANAGER_URL@@, @@AGENT_VERSION@@ and
// @@RELEASE_PUBKEY_PEM@@ are substituted at serve time (worker/src/install/).
//
// Also generates worker/.generated/ui-assets.ts. With EXP_EMBED_UI=1 (deploy.sh --embed-ui) it holds the built admin UI
// (ui/dist) as a frozen map plus the "/*" rules of dist/_headers; otherwise the SAME module with an EMPTY map (so imports
// always resolve and the default bundle does not grow). EXP_UI_DIST overrides the dist directory (tests only).
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const managerDir = resolve(here, "..");
// EXP_AGENT_INSTALL_SH / EXP_PREPARE_OUT exist for the tests of this script only
const real = process.env.EXP_AGENT_INSTALL_SH ? resolve(process.env.EXP_AGENT_INSTALL_SH) : resolve(managerDir, "..", "agent", "install", "install.sh");

const PLACEHOLDER = `#!/bin/sh
# exp agent bootstrap placeholder: the real install.sh (WP-6) is not bundled into this manager build.
# manager: @@MANAGER_URL@@   agent: @@AGENT_VERSION@@
EXP_RELEASE_PUBKEY_PEM='@@RELEASE_PUBKEY_PEM@@'
echo "agent bootstrap not built yet" >&2
exit 1
`;

const usingReal = existsSync(real);
const script = usingReal ? readFileSync(real, "utf8") : PLACEHOLDER;
const outDir = process.env.EXP_PREPARE_OUT ? resolve(process.env.EXP_PREPARE_OUT) : join(managerDir, "worker", ".generated");
mkdirSync(outDir, { recursive: true });
const body =
  "// GENERATED by scripts/prepare.mjs - do not edit, do not commit.\n" +
  `export const INSTALL_SH_SOURCE: "agent/install/install.sh" | "placeholder" = ${JSON.stringify(usingReal ? "agent/install/install.sh" : "placeholder")};\n` +
  `export const INSTALL_SH: string = ${JSON.stringify(script)};\n`;
const target = join(outDir, "install-sh.ts");
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  current = "";
}
if (current !== body) writeFileSync(target, body);
console.log(`prepare: install.sh from ${usingReal ? real : "placeholder"}`);

// ---- embedded admin UI ----------------------------------------------------------------------------------------
const MAX_FILE = 2 * 1024 * 1024;
const MAX_TOTAL = 8 * 1024 * 1024;
const TYPES = {
  html: "text/html; charset=utf-8",
  js: "text/javascript; charset=utf-8",
  mjs: "text/javascript; charset=utf-8",
  css: "text/css; charset=utf-8",
  svg: "image/svg+xml",
  png: "image/png",
  ico: "image/x-icon",
  json: "application/json; charset=utf-8",
  woff2: "font/woff2",
  txt: "text/plain; charset=utf-8",
};

function fail(msg) {
  console.error(`prepare: ${msg}`);
  process.exit(1);
}

function readDist(root) {
  const files = {};
  let total = 0;
  const walk = (dir, rel) => {
    for (const ent of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const abs = join(dir, ent.name);
      const key = `${rel}/${ent.name}`;
      const st = lstatSync(abs);
      if (st.isSymbolicLink()) fail(`refusing symlink in the UI dist: ${key}`);
      if (st.isDirectory()) {
        walk(abs, key);
        continue;
      }
      if (!st.isFile()) fail(`refusing non-regular file in the UI dist: ${key}`);
      if (key === "/_headers") continue;
      if (st.size > MAX_FILE) fail(`${key} is larger than 2 MiB`);
      total += st.size;
      if (total > MAX_TOTAL) fail("the UI dist is larger than 8 MiB in total");
      const buf = readFileSync(abs);
      const ext = ent.name.includes(".") ? ent.name.split(".").pop().toLowerCase() : "";
      files[key] = {
        type: TYPES[ext] ?? "application/octet-stream",
        b64: buf.toString("base64"),
        etag: `"${createHash("sha256").update(buf).digest("hex")}"`,
      };
    }
  };
  walk(root, "");
  if (!files["/index.html"]) fail("the UI dist has no index.html");
  return files;
}

// Strict parser for the "/*" block of dist/_headers: `/*` at column 0, then indented `Name: value` lines.
function parseHeaders(text) {
  const rules = [];
  let inStar = false;
  let seen = false;
  for (const raw of text.replace(/\r\n/g, "\n").split("\n")) {
    if (raw.trim() === "" || raw.trimStart().startsWith("#")) continue;
    if (!/^\s/.test(raw)) {
      if (raw.trim() !== "/*") fail(`_headers: unsupported rule "${raw.trim()}" (only the "/*" block is supported)`);
      if (seen) fail('_headers: duplicate "/*" block');
      inStar = seen = true;
      continue;
    }
    if (!inStar) fail("_headers: header line before any block");
    const m = /^\s+([A-Za-z][A-Za-z0-9-]*):[ \t]*(.+?)\s*$/.exec(raw);
    if (!m) fail(`_headers: unsupported syntax "${raw.trim()}"`);
    if (/[\x00-\x1f\x7f]/.test(m[2])) fail("_headers: control character in a value");
    rules.push([m[1], m[2]]);
  }
  if (!seen || rules.length === 0) fail('_headers: no "/*" block');
  return rules;
}

let assets = {};
let rules = [];
if (process.env.EXP_EMBED_UI === "1") {
  const dist = process.env.EXP_UI_DIST ? resolve(process.env.EXP_UI_DIST) : join(managerDir, "ui", "dist");
  if (!existsSync(dist)) fail(`EXP_EMBED_UI=1 but ${dist} does not exist (build the UI first)`);
  assets = readDist(dist);
  const hp = join(dist, "_headers");
  if (!existsSync(hp)) fail("EXP_EMBED_UI=1 but dist/_headers is missing (the CSP must travel with the UI)");
  rules = parseHeaders(readFileSync(hp, "utf8"));
}
const uiBody =
  "// GENERATED by scripts/prepare.mjs - do not edit, do not commit.\n" +
  "// Empty unless built with EXP_EMBED_UI=1 (deploy.sh --embed-ui).\n" +
  "export interface UiAsset { readonly type: string; readonly b64: string; readonly etag: string }\n" +
  `export const UI_ASSETS: Readonly<Record<string, UiAsset>> = Object.freeze(${JSON.stringify(assets)});\n` +
  `export const UI_HEADERS: readonly (readonly [string, string])[] = Object.freeze(${JSON.stringify(rules)});\n`;
const uiTarget = join(outDir, "ui-assets.ts");
let uiCurrent = "";
try {
  uiCurrent = readFileSync(uiTarget, "utf8");
} catch {
  uiCurrent = "";
}
if (uiCurrent !== uiBody) writeFileSync(uiTarget, uiBody);
console.log(`prepare: ui assets ${Object.keys(assets).length ? `embedded (${Object.keys(assets).length} files)` : "not embedded"}`);
